// ============================================
// Reveal على Scroll
// ============================================
function setupReveal() {
  const items = document.querySelectorAll('section > .wrap > *, section > .wrap-narrow > *');
  items.forEach(el => el.classList.add('reveal'));

  // إظهار فوري للعناصر الموجودة في النافذة الآن (above the fold)
  const vh = window.innerHeight || document.documentElement.clientHeight;
  items.forEach(el => {
    const r = el.getBoundingClientRect();
    if (r.top < vh - 40) el.classList.add('in');
  });

  // مُراقب لما يدخل لاحقاً عند التمرير
  if ('IntersectionObserver' in window) {
    const io = new IntersectionObserver((entries) => {
      entries.forEach(e => {
        if (e.isIntersecting) {
          e.target.classList.add('in');
          io.unobserve(e.target);
        }
      });
    }, { threshold: 0.08, rootMargin: '0px 0px -40px 0px' });
    items.forEach(el => {
      if (!el.classList.contains('in')) io.observe(el);
    });
  } else {
    // fallback
    items.forEach(el => el.classList.add('in'));
  }

  // ضمان نهائي — لو حصل أي خلل، نُظهر كل شيء بعد ٢ ثانية
  setTimeout(() => {
    items.forEach(el => el.classList.add('in'));
  }, 2000);
}

