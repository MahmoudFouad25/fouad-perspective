/* بناء المعرّف من المفاتيح الثلاثة */
BURN_CONTENT_TARGET.keyOf = function (axis, dim, cls) {
  return "TGT_" + String(axis || "").toUpperCase() + "_" +
         String(dim || "").toUpperCase() + "_" +
         String(cls || "").toUpperCase();
};

/* الكتلة المطابقة لنتيجة المشارك */
BURN_CONTENT_TARGET.get = function (axis, dim, cls) {
  return BURN_CONTENT_TARGET[BURN_CONTENT_TARGET.keyOf(axis, dim, cls)] || null;
};

BURN_CONTENT_TARGET.byId = function (id) {
  return BURN_CONTENT_TARGET[id] || null;
};

/* ── تقييم شرط الفقرة المشروطة ──
   ★ لا eval ولا Function. مقيّمٌ محدودٌ يفهم صيغةً واحدةً فقط:
     "متغيّر عامل رقم" مفصولةً بـ ||
   والمتغيّرات مأخوذةٌ من سياقٍ يبنيه الجسر لا من نطاقٍ مفتوح. */
BURN_CONTENT_TARGET.testCondition = function (expr, ctx) {
  if (!expr) return false;
  ctx = ctx || {};
  var clauses = String(expr).split("||");
  for (var i = 0; i < clauses.length; i++) {
    var m = clauses[i].trim().match(/^([A-Za-z0-9_]+)\s*(>=|<=|>|<|==)\s*(-?\d+(?:\.\d+)?)$/);
    if (!m) continue;
    var name = m[1], op = m[2], num = parseFloat(m[3]);
    var v = ctx[name];
    if (typeof v !== "number" || isNaN(v)) continue;
    var ok = (op === ">=") ? (v >= num)
           : (op === "<=") ? (v <= num)
           : (op === ">")  ? (v >  num)
           : (op === "<")  ? (v <  num)
           : (v === num);
    if (ok) return true;
  }
  return false;
};

/* ── تركيب الكتلة الجاهزة للعرض ──
   يُرجع كائنًا بنفس عقد burn-render.contentBlock:
     { id, title, body, style, conditionalBody? }
   ★ والفقرة المشروطة تُحذَف بالكامل عند عدم تحقّق شرطها،
     ولا تُستبدَل بشيء. */
BURN_CONTENT_TARGET.resolve = function (axis, dim, cls, ctx, vars) {
  var block = BURN_CONTENT_TARGET.get(axis, dim, cls);
  if (!block) return null;

  function sub(s) {
    if (!vars) return s;
    return String(s || "").replace(/\{(\w+)\}/g, function (m, k) {
      return (vars[k] !== undefined && vars[k] !== null) ? String(vars[k]) : m;
    });
  }

  var out = {
    id: block.id,
    section: block.section,
    screen: block.screen,
    style: block.style || null,
    title: block.title ? sub(block.title) : null,
    body: (block.body || []).map(sub)
  };

  if (block.conditional &&
      BURN_CONTENT_TARGET.testCondition(block.conditional.when, ctx)) {
    out.conditionalBody = (block.conditional.body || []).map(sub);
  }

  return out;
};

/* ════════════════════════════════════════════════════════════════════════
   تحقّق السلامة
   ════════════════════════════════════════════════════════════════════════ */
BURN_CONTENT_TARGET.verify = function () {
  var issues = [];
  var axes = ["coh", "vit", "bel"];
  var dims = ["d1", "d2", "d3"];
  var classes = ["exc", "def", "osc", "tlt"];
  var count = 0;
  var conditionals = [];

  axes.forEach(function (ax) {
    dims.forEach(function (d) {
      classes.forEach(function (c) {
        var id = BURN_CONTENT_TARGET.keyOf(ax, d, c);
        var b = BURN_CONTENT_TARGET[id];

        if (!b) { issues.push("كتلة مفقودة: " + id); return; }
        count++;

        /* اتّساق الوسوم الداخليّة مع المعرّف */
        if (b.axis !== ax) issues.push(id + ": حقل axis غير مطابق");
        if (b.dim !== d)   issues.push(id + ": حقل dim غير مطابق");
        if (b.cls !== c)   issues.push(id + ": حقل cls غير مطابق");

        if (!Array.isArray(b.body) || !b.body.length) {
          issues.push(id + ": body فارغ"); return;
        }

        /* ★ البنية الخماسيّة: خمس فقراتٍ في حالات النزيف، وأربعٌ في الميل.
           والتذبذب يُسمَح له بست فقرات، لأنّه يشرح الحلقة كاملة —
           وبدون شرحها لا ينكسر اللوم. */
        var n = b.body.length;
        if (c === "tlt") {
          if (n !== 4) issues.push(id + ": فقرات الميل " + n + " والمتوقَّع ٤");
        } else if (c === "osc") {
          if (n < 5 || n > 6) issues.push(id + ": فقرات التذبذب " + n + " والمتوقَّع ٥–٦");
        } else {
          if (n !== 5) issues.push(id + ": الفقرات " + n + " والمتوقَّع ٥");
        }

        /* ★ التسمية أوّلًا دائمًا: الفقرة الأولى تحمل «بُعدك» */
        if (b.body[0].indexOf("بُعدك") !== 0) {
          issues.push(id + ": الفقرة الأولى لا تبدأ بالتسمية");
        }

        /* ★ كتل التذبذب تفتح بكسر اللوم في الفقرة الثانية،
           لأنّ صاحبها يلوم نفسه فيزيد الإمساك فيزيد الانفلات. */
        if (c === "osc" && b.body[1].indexOf("ليس") === -1) {
          issues.push(id + ": كتلة تذبذبٍ لا تكسر اللوم في فقرتها الثانية");
        }

        /* ★ كتل التفريط تحمل إعادة تعريفٍ صريحة: ليس كسلًا ولا برودًا ولا أنانيّة */
        if (c === "def") {
          var hasRedef = b.body.some(function (p) {
            return /(?:وهذا|ولم يكن|وليس)\s+ليس|ليس (?:إهمالًا|استهتارًا|ضعفًا|تواضعًا|رضًا|برودًا|أنانيّة)/.test(p);
          });
          if (!hasRedef) issues.push(id + ": كتلة تفريطٍ بلا إعادة تعريفٍ صريحة");
        }

        /* ★ كل كتلة نزيفٍ تُغلَق ببابٍ لا بكشف */
        if (c !== "tlt") {
          var last = b.body[b.body.length - 1];
          if (last.indexOf("ولن نطلب") !== 0 && last.indexOf("سنطلب") === -1 && last.indexOf("سنبدأ") === -1) {
            issues.push(id + ": الفقرة الأخيرة لا تفتح بابًا");
          }
        }

        /* الفقرة المشروطة */
        if (b.conditional) {
          conditionals.push(id);
          if (!b.conditional.when) issues.push(id + ": فقرةٌ مشروطةٌ بلا شرط");
          if (!Array.isArray(b.conditional.body) || !b.conditional.body.length)
            issues.push(id + ": فقرةٌ مشروطةٌ بلا نصّ");
        }
      });
    });
  });

  /* ★ الباب المشروط في كتلتين فقط — والتنبيه الذي يُعطى للجميع لا يُقرَأ من أحد */
  if (conditionals.length !== 2) {
    issues.push("الفقرات المشروطة " + conditionals.length + " والمتوقَّع ٢ — وُجدت في: " +
                (conditionals.join("، ") || "لا شيء"));
  }

  return {
    ok: issues.length === 0,
    issues: issues,
    count: count,
    conditionals: conditionals
  };
};

