/* حقن القيم: fill("الجرعة {n} من {total}", {n:3, total:6}) */
BURN_STRINGS.fill = function (template, vars) {
  if (!template) return "";
  if (!vars) return template;
  return String(template).replace(/\{(\w+)\}/g, function (m, key) {
    return (vars[key] !== undefined && vars[key] !== null) ? String(vars[key]) : m;
  });
};

/* وصولٌ بمسارٍ نقطيّ: get("dose.closing.3.head") */
BURN_STRINGS.get = function (path, vars) {
  var parts = String(path || "").split(".");
  var cur = BURN_STRINGS;
  for (var i = 0; i < parts.length; i++) {
    if (cur == null) return "";
    cur = cur[parts[i]];
  }
  if (typeof cur !== "string") return cur || "";
  return vars ? BURN_STRINGS.fill(cur, vars) : cur;
};

/* الأرقام العربيّة الهنديّة — تُستعمل في الترويسات والعدّادات */
BURN_STRINGS.arabicNum = function (n) {
  var map = ["٠","١","٢","٣","٤","٥","٦","٧","٨","٩"];
  return String(n).replace(/\d/g, function (d) { return map[+d]; });
};

/* أسماء الجرعات بالحروف — تُستعمل في رسائل كوتش الجيب */
BURN_STRINGS.doseName = function (n) {
  var names = { 1:"الأولى", 2:"التانية", 3:"التالتة", 4:"الرابعة", 5:"الخامسة", 6:"السادسة" };
  return names[n] || String(n);
};

/* اختيار نصّ التعليق على حركة الخطّ.
   delta = الفرق عن الأسبوع السابق · week = رقم الأسبوع · isFirst = أوّل نقطة */
BURN_STRINGS.lineComment = function (delta, week, isFirst, expectedDipWeeks, significantChange) {
  var C = BURN_STRINGS.pulse.comment;
  if (isFirst) return C.first;
  if (expectedDipWeeks && expectedDipWeeks.indexOf(week) > -1) return C.expectedDip;
  var gap = (typeof significantChange === "number") ? significantChange : 0.5;
  if (delta <= -gap) return C.down;
  if (delta >= gap)  return C.up;
  return C.flat;
};

/* ════════════════════════════════════════════════════════════════════════
   تحقّق السلامة — يتأكّد من عدم وجود نصٍّ فارغٍ في المواضع الإلزاميّة.
   ════════════════════════════════════════════════════════════════════════ */
BURN_STRINGS.verify = function () {
  var issues = [];

  /* إغلاقات الجرعات الستّ */
  for (var d = 1; d <= 6; d++) {
    var c = BURN_STRINGS.dose.closing[d];
    if (!c || !c.head) issues.push("إغلاق الجرعة " + d + " ناقص");
    if (!BURN_STRINGS.dose.openTitle[d]) issues.push("عنوان فتح الجرعة " + d + " ناقص");
  }

  /* أزرار الانتقال بين شاشتَي النتيجة */
  if (!BURN_STRINGS.result.nextScreen[1] || !BURN_STRINGS.result.nextScreen[2])
    issues.push("أزرار الانتقال بين شاشات النتيجة ناقصة");

  /* التعليقات الخمسة على حركة الخطّ */
  ["down","up","flat","expectedDip","first"].forEach(function (k) {
    if (!BURN_STRINGS.pulse.comment[k] || !BURN_STRINGS.pulse.comment[k].head)
      issues.push("تعليق الخطّ ناقص: " + k);
  });

  /* رسائل كوتش الجيب الأساسيّة */
  ["doseReady","afterResult","gap2Days","gap5Days","lineDown","lineUp",
   "bottomWeek","vent","escalate"].forEach(function (k) {
    if (!BURN_STRINGS.coach[k]) issues.push("رسالة كوتش ناقصة: " + k);
  });

  /* أسماء العلامات التسع عشرة */
  var flagCount = Object.keys(BURN_STRINGS.admin.flagNames).length;
  if (flagCount !== 19) issues.push("أسماء العلامات: " + flagCount + " والمتوقَّع ١٩");

  /* أسماء حالات الطيف الخمس */
  var stateCount = Object.keys(BURN_STRINGS.labels.stateNames).length;
  if (stateCount !== 5) issues.push("أسماء حالات الطيف: " + stateCount + " والمتوقَّع ٥");

  return { ok: issues.length === 0, issues: issues };
};

