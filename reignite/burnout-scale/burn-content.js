/* حقن الوسوم داخل نصوص الكتلة */
BURN_CONTENT.fill = function (block, vars) {
  if (!block) return null;
  if (!vars) return block;
  function sub(s) {
    return String(s || "").replace(/\{(\w+)\}/g, function (m, k) {
      return (vars[k] !== undefined && vars[k] !== null) ? String(vars[k]) : m;
    });
  }
  var out = {
    id: block.id,
    section: block.section,
    screen: block.screen,
    style: block.style || null,
    title: block.title ? sub(block.title) : null,
    body: (block.body || []).map(sub)
  };
  if (block.intro) out.intro = sub(block.intro);
  if (block.outro) out.outro = sub(block.outro);
  return out;
};

