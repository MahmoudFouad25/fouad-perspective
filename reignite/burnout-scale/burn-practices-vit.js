BURN_PRACTICES_VIT.keyOf = function (dim, state) {
  return "PRC_VIT_" + String(dim || "").toUpperCase() + "_" + String(state || "").toUpperCase();
};

BURN_PRACTICES_VIT.get = function (dim, state) {
  return BURN_PRACTICES_VIT[BURN_PRACTICES_VIT.keyOf(dim, state)] || null;
};

BURN_PRACTICES_VIT.byId = function (id) {
  return BURN_PRACTICES_VIT[id] || null;
};

BURN_PRACTICES_VIT.roleVariant = function (id, role) {
  var p = BURN_PRACTICES_VIT[id];
  if (!p || !p.roles) return null;
  return p.roles[role] || p.roles.lead || null;
};

/* ════════════════════════════════════════════════════════════════════════
   تحقّق السلامة — بمعايير التماسك، زائد المعيار الثامن الخاصّ بالحيوية
   ════════════════════════════════════════════════════════════════════════ */
BURN_PRACTICES_VIT.verify = function () {
  var issues = [];
  var dims = ["d1", "d2", "d3"];
  var states = ["exc", "def", "osc"];
  var roles = ["lead", "mgr", "found", "free", "sale", "hr"];
  var required = ["what", "when", "avoid", "why", "successSign", "failurePermission"];
  var count = 0, variants = 0, heaviest = 0, referrals = [];

  dims.forEach(function (d) {
    states.forEach(function (s) {
      var id = BURN_PRACTICES_VIT.keyOf(d, s);
      var p = BURN_PRACTICES_VIT[id];
      if (!p) { issues.push("ممارسة مفقودة: " + id); return; }
      count++;

      if (p.axis !== "vit") issues.push(id + ": حقل axis غير مطابق");
      if (p.dim !== d)      issues.push(id + ": حقل dim غير مطابق");
      if (p.state !== s)    issues.push(id + ": حقل state غير مطابق");
      if (!p.name)          issues.push(id + ": بلا اسم");

      required.forEach(function (f) {
        if (!p[f] || !String(p[f]).trim()) issues.push(id + ": حقل " + f + " فارغ");
      });

      /* المعيار الأوّل — وظيفيّة */
      if (/^(حاول|اسمح لنفسك|تأمّل|اشعر|تحمّس)/.test(String(p.what).trim())) {
        issues.push(id + ": what تبدأ بصيغةٍ غير وظيفيّة");
      }

      /* المعيار الثاني — الجلسة والعبء */
      if (typeof p.minutes !== "number" || p.minutes > 10) {
        issues.push(id + ": الجلسة " + p.minutes + " دقيقة والحدّ عشر");
      }
      var perWeek = (p.frequency === "daily") ? 7
                  : (p.frequency === "biweekly") ? 3.5
                  : (p.frequency === "weekly") ? 1
                  : 0.1;
      var w = p.minutes * perWeek;
      if (w > heaviest) heaviest = w;
      if (w > 40) issues.push(id + ": العبء الأسبوعيّ " + w + " دقيقة والسقف ٤٠");

      /* المعيار الرابع — علامةٌ محسوسة */
      if (/تشعر بتحسّن|تصير أسعد|تستمتع أكثر/.test(String(p.successSign))) {
        issues.push(id + ": علامة النجاح شعوريّةٌ لا محسوسة");
      }

      /* ★ المعيار الثامن — لا تفترض رغبةً، ولا تطلب مقدارًا، ولا تقيس بالمتعة */
      var joined = [p.what, p.when, p.successSign].join(" ");
      if (/افعل ما تحبّه|شيئًا تستمتع به|ما يُسعدك/.test(joined)) {
        issues.push(id + ": تفترض وجود رغبة — مخالفةٌ للمعيار الثامن");
      }
      if (/ثلاثة أشياء|خمسة أشياء|قائمةً من/.test(String(p.what))) {
        issues.push(id + ": تطلب مقدارًا — مخالفةٌ للمعيار الثامن");
      }

      /* المعيار السادس — لا أدوات */
      if (/تطبيق|أبليكيشن|جدول إكسل/.test(String(p.what))) {
        issues.push(id + ": تتطلّب أداةً — حِملٌ إضافيّ");
      }

      if (p.referralNote) referrals.push(id);

      if (!p.roles) { issues.push(id + ": بلا نسخٍ سياقيّة"); return; }
      roles.forEach(function (r) {
        if (!p.roles[r] || !String(p.roles[r]).trim()) issues.push(id + ": نسخة " + r + " ناقصة");
        else variants++;
      });
    });
  });

  /* ★ الباب المشروط في هذا الفرع: ممارسةٌ واحدةٌ فقط — التبلّد.
     والتنبيه الذي يُعطى للجميع لا يُقرَأ من أحد. */
  if (referrals.length !== 1 || referrals[0] !== "PRC_VIT_D1_DEF") {
    issues.push("ملاحظة الإحالة متوقّعةٌ في PRC_VIT_D1_DEF وحدها — وُجدت في: " +
                (referrals.join("، ") || "لا شيء"));
  }

  return {
    ok: issues.length === 0,
    issues: issues,
    count: count,
    variants: variants,
    heaviestWeeklyMinutes: Math.round(heaviest),
    referrals: referrals
  };
};

