function mzCompute(me) {
  me = me || {};
  var sc = { H: 0, V: 0, B: 0 }, used = { sit: 0, keys: 0 };
  ["sit1", "sit2", "sit3"].forEach(function (k) { if (sc.hasOwnProperty(me[k])) { sc[me[k]] += 2; used.sit++; } });
  ["k1", "k2", "k3", "k4"].forEach(function (k) {
    var r = me[k]; if (!r || r.length < 1) return;
    used.keys++;
    if (sc.hasOwnProperty(r[0])) sc[r[0]] += 3;
    if (r[1] && sc.hasOwnProperty(r[1])) sc[r[1]] += 1;
  });
  var calc = ["H", "V", "B"].sort(function (a, b) { return sc[b] - sc[a] || "BVH".indexOf(a) - "BVH".indexOf(b); });
  var order = (me.override && me.override.length === 3) ? me.override.slice() : calc;
  var close = [];
  if (Math.abs(sc[calc[0]] - sc[calc[1]]) <= 2) close.push([calc[0], calc[1]]);
  if (Math.abs(sc[calc[1]] - sc[calc[2]]) <= 2) close.push([calc[1], calc[2]]);
  var allClose = (sc[calc[0]] - sc[calc[2]]) <= 2;
  var felt = (me.felt && me.felt.length === 3) ? me.felt : null;
  var feltDiffers = !!(felt && felt.join("") !== order.join(""));

  /* الأبعاد */
  var dims = {};
  ["H", "V", "B"].forEach(function (a) { [1, 2, 3].forEach(function (n) {
    var k = a + n; dims[k] = (me[k] === undefined || me[k] === null || me[k] === "") ? null : +me[k];
  }); });
  /* زيادة في بعد + ناقصة في بعد من محور تاني = «ساعات بيبقوا وش واحد» */
  var link = null;
  Object.keys(dims).forEach(function (p) {
    if (link || dims[p] === null || dims[p] < 2) return;
    Object.keys(dims).forEach(function (m) {
      if (link || dims[m] === null || dims[m] > -2 || m[0] === p[0]) return;
      link = [p, m];
    });
  });
  if (!link) Object.keys(dims).forEach(function (p) {
    if (link || dims[p] === null || dims[p] < 1) return;
    Object.keys(dims).forEach(function (m) {
      if (link || dims[m] === null || dims[m] > -1 || m[0] === p[0]) return;
      link = [p, m];
    });
  });

  /* الدواير */
  var hot = [];
  ["B", "V", "H"].forEach(function (a) {
    var v = me["cy" + a]; if (!v || v === "no") return;
    if (MZ_CYCLES[a].danger.indexOf(+v) !== -1) hot.push({ ax: a, st: +v });
  });

  var first = order[0], hidden = order[2];
  return {
    sc: sc, order: order, calc: calc, close: close, allClose: allClose, felt: felt, feltDiffers: feltDiffers,
    dims: dims, link: link, hot: hot, first: first, hidden: hidden,
    gift: MZ_GIFTS[hidden], combo: MZ_COMBOS[first + hidden], used: used,
    thin: (used.keys === 0 && used.sit < 3)
  };
}

