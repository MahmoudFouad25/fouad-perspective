  var STRENGTHS_CONTENT = {};
  function add(batch) {
    if (!batch || typeof batch !== 'object') return;
    for (var k in batch) {
      if (Object.prototype.hasOwnProperty.call(batch, k)) STRENGTHS_CONTENT[k] = batch[k];
    }
  }

