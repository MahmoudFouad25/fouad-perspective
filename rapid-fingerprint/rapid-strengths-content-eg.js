  /* ════════════════ لا تعديل تحت هذا السطر ════════════════ */
  function getStrengthContent(strengthId) {
    if (!strengthId) return null;
    var c = STRENGTHS_CONTENT[strengthId];
    if (!c) return null;
    if (!c.define || !c.balance || !c.excess || !c.deficit || !c.seed) return null;
    return c;
  }

  var API = { STRENGTHS_CONTENT: STRENGTHS_CONTENT, getStrengthContent: getStrengthContent };
  if (typeof module !== 'undefined' && module.exports) { module.exports = API; }
  global.RAPID_STRENGTHS_CONTENT_EG = API;

