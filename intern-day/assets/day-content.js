function dayMovementNo(st) {
  var m = (st && st.mv || "").match(/[٠-٩]+/);
  if (!m) return 0;
  return parseInt(String(m[0]).replace(/[٠-٩]/g, function (c) {
    return "٠١٢٣٤٥٦٧٨٩".indexOf(c);
  }), 10) || 0;
}

